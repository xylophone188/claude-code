// gen-omniroute-providers.mjs
//
// Reads the upstream 9router (OmniRoute) provider registry and emits a ccb
// (claude-code-best) compatible provider catalog:
//   src/services/providerRegistry/omnirouteProviders.generated.ts
//
// Source of truth: a copy of github.com/decolua/9router's open-sse/providers
// exported as ESM (type:module) under /tmp/omni-providers/registry/*.js.
//
// Each upstream provider object:
//   { id, alias, uiAlias, display, category, authType, authModes,
//     transport: { baseUrl, validateUrl }, models: [...], passthroughModels }
//
// is mapped to ccb's ProviderConfig:
//   { id, kind:'openai-compat', baseUrl, apiKeyEnv, defaultModel, compatRule }
//
// Transform notes:
//   - ccb's OpenAI SDK appends `/chat/completions` to baseUrl, so upstream
//     baseUrls ending in `/chat/completions` are stripped to the bare base.
//   - Anthropic-style endpoints (baseUrl ends with `/messages`) are skipped:
//     ccb already speaks Anthropic natively (PR-2 only supports openai-compat).
//   - Keyless providers keep a derived apiKeyEnv name; ccb sends an empty
//     bearer when the env var is unset, which keyless endpoints accept.

import { readdir, writeFile } from 'node:fs/promises'
import { pathToFileURL } from 'node:url'
import { join } from 'node:path'

const REGISTRY_DIR =
  process.env.OMNI_REGISTRY_DIR || '/tmp/omni-providers/registry'
const OUT = new URL(
  '../src/services/providerRegistry/omnirouteProviders.generated.ts',
  import.meta.url,
)

const COMPAT_BY_ID = {
  groq: 'groq',
  deepseek: 'deepseek',
  cerebras: 'cerebras',
}

function sanitizeId(id) {
  const cleaned = String(id)
    .toLowerCase()
    .replace(/[^a-z0-9-]/g, '-')
    .replace(/-+/g, '-')
    .replace(/^-|-$/g, '')
  return cleaned || 'unknown'
}

function mapProvider(p) {
  const rawId = p?.id
  if (!rawId) return null
  const id = sanitizeId(rawId)

  const baseUrl = p?.transport?.baseUrl
  if (typeof baseUrl !== 'string' || !baseUrl.startsWith('http')) return null
  // Anthropic-style upstream endpoint: ccb handles Anthropic natively (PR-2).
  if (baseUrl.endsWith('/messages')) return null

  let openaiBase = baseUrl
  if (openaiBase.endsWith('/chat/completions')) {
    openaiBase = openaiBase.slice(0, -'/chat/completions'.length)
  }

  const models = Array.isArray(p.models) ? p.models : []
  const defaultModel =
    models.length > 0 && models[0]?.id
      ? String(models[0].id)
      : p.uiAlias || p.alias || id

  const apiKeyEnv = `OMNI_${id.toUpperCase().replace(/-/g, '_')}_KEY`

  const compatRule = COMPAT_BY_ID[id] || 'permissive'

  return {
    id,
    kind: 'openai-compat',
    baseUrl: openaiBase,
    apiKeyEnv,
    defaultModel,
    compatRule,
  }
}

async function main() {
  const files = (await readdir(REGISTRY_DIR)).filter(f => f.endsWith('.js'))
  const out = []
  const seen = new Set()
  const skipped = []
  const failed = []

  for (const f of files) {
    if (f === 'index.js') continue
    const url = pathToFileURL(join(REGISTRY_DIR, f)).href
    let mod
    try {
      mod = await import(url)
    } catch (err) {
      failed.push(`${f}: ${err?.message || err}`)
      continue
    }
    const p = mod?.default
    if (!p || typeof p !== 'object') continue
    const mapped = mapProvider(p)
    if (!mapped) {
      skipped.push(f)
      continue
    }
    if (seen.has(mapped.id)) continue
    seen.add(mapped.id)
    out.push(mapped)
  }

  out.sort((a, b) => a.id.localeCompare(b.id))

  const header = `// AUTO-GENERATED by scripts/gen-omniroute-providers.mjs
// Source: upstream 9router (OmniRoute) open-sse/providers/registry
// Do not edit by hand. Regenerate with: bun run scripts/gen-omniroute-providers.mjs
import type { ProviderConfig } from './types.js'

export const OMNIROUTE_PROVIDERS: ProviderConfig[] = [
`

  const body = out
    .map(
      p =>
        `  {\n` +
        `    id: ${JSON.stringify(p.id)},\n` +
        `    kind: 'openai-compat',\n` +
        `    baseUrl: ${JSON.stringify(p.baseUrl)},\n` +
        `    apiKeyEnv: ${JSON.stringify(p.apiKeyEnv)},\n` +
        `    defaultModel: ${JSON.stringify(p.defaultModel)},\n` +
        `    compatRule: ${JSON.stringify(p.compatRule)},\n` +
        `  },`,
    )
    .join('\n')

  const footer = `\n]\n`

  await writeFile(new URL(OUT), header + body + footer, 'utf-8')

  console.log(`Generated ${out.length} omniroute providers -> ${OUT.pathname}`)
  console.log(`  skipped (anthropic-style / non-http): ${skipped.length}`)
  console.log(`  failed to import: ${failed.length}`)
  for (const f of failed) console.log(`    - ${f}`)
}

main().catch(e => {
  console.error(e)
  process.exit(1)
})
